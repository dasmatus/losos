#!/usr/bin/env bun
// Regenerates src/css/derisk-theme.css from an mcsapi checkout.
// Shim target for derisk-theme.sh.
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

function run(cmd: string[], cwd?: string) {
  const p = spawnSync(cmd[0], cmd.slice(1), { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (p.status !== 0) throw new Error(p.stderr || p.stdout || cmd.join(" "));
  return p.stdout;
}

const mcsapiArg = Bun.argv[2];
if (!mcsapiArg) {
  process.stderr.write("usage: derisk-theme.sh /path/to/mcsapi\n");
  process.exit(2);
}
const mcsapi = resolve(mcsapiArg);
const here = resolve(import.meta.dir, "..");
const out = join(here, "src/css/derisk-theme.css");
const rev = run(["git", "-C", mcsapi, "rev-parse", "--short", "HEAD"]).trim();
const work = mkdtempSync(join(tmpdir(), "derisk-theme-"));
try {
  mkdirSync(join(work, "src"), { recursive: true });
  writeFileSync(join(work, "Cargo.toml"), `[package]
name = "derisk-theme-css"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
mcsapi-theme = { path = "${mcsapi}/crates/mcsapi-theme" }

[workspace]
`);
  writeFileSync(join(work, "src/main.rs"), `fn main() {
    let id = std::env::args().nth(1).expect("theme ID");
    let theme = mcsapi_theme::Theme::builtin(&id).expect("built-in theme");
    print!("{}", mcsapi_theme::export::css_variables(&theme));
}
`);
  const declarations = (id: string, indent: string) =>
    run(["cargo", "run", "--quiet", "--manifest-path", join(work, "Cargo.toml"), "--", id])
      .split("\n")
      .slice(1, -2)
      .map((l) => l.replace(/^  --/, "  --derisk-"))
      .map((l) => `${indent}${l}`)
      .join("\n");
  const light = declarations("derisk-light", "");
  const dark = declarations("derisk-dark", "  ");
  const darkRoot = declarations("derisk-dark", "");
  writeFileSync(out, `/* The LosOS desktop's theme, generated by scripts/derisk-theme.sh from
 * mcsapi ${rev} (mcsapi-theme, export::css_variables of derisk-light and
 * derisk-dark). Do not edit: change the desktop theme in mcsapi and run the
 * script again.
 *
 * Bare :root is the light theme. The media arm switches to dark unless the
 * reader picked Light, and the explicit-dark rule comes last at equal
 * specificity so a picked Dark wins the other way. Docusaurus sets
 * data-theme="light|dark" on <html>. Without JavaScript nothing sets it,
 * and the theme control's checked radio (ColorModeToggle) picks instead. */

:root {
${light}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]):not(:has(.hb-theme__radio[value="light"]:checked)) {
${dark}
  }
}

:root[data-theme="dark"],
:root:not([data-theme]):has(.hb-theme__radio[value="dark"]:checked) {
${darkRoot}
}
`);
  console.log(`wrote ${out} from mcsapi ${rev}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
