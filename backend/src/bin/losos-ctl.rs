//! `losos-ctl` — the facade CLI.
//!
//! Most subcommands relay to `lososd` over the system bus and print the JSON it
//! replies with, followed by a newline. The daemon does the privileged work;
//! this binary needs nothing but the right to send on the bus.
//!
//! `install` is the exception: it runs entirely locally. It is the installer
//! ISO's entry point, where there is no daemon and no bus to talk to.
//!
//! `--json` is accepted on the read-only subcommands and does nothing: output
//! has always been JSON, and the flag exists so older callers keep working.

use clap::{Args, Parser, Subcommand};
use losos_ctl::facade::{call_backend, BackendFailure};
use losos_ctl::install_report;
use losos_ctl::install_screen;
use losos_ctl::installer::{parse_tang, resolve_tpm, staged_claim, Tang};
use losos_ctl::installer_io::{
    booted_in_bios, load_gpg_keys, options_from_env, request_edge_tang, run_install,
    secure_boot_state, tpm_present, Splash,
};
use losos_ctl::model::Mode;
use losos_ctl::overrides::validate_apply;
use losos_report::{github, install, Report, Target};
use std::io::{IsTerminal, Read, Write};
use std::path::PathBuf;
use std::process::ExitCode;
use std::time::{Duration, Instant};

#[derive(Parser)]
#[command(
    name = "losos-ctl",
    about = "losos appliance control facade (D-Bus client for lososd)",
    version
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Print the current mode and sharing flag.
    State {
        /// Accepted for compatibility; output is always JSON.
        #[arg(long)]
        json: bool,
    },
    /// Apply a new mode and trigger a rebuild.
    Change {
        /// Sharing posture: local (private) or mesh (contribute storage).
        #[arg(long, value_parser = parse_mode)]
        mode: Mode,
    },
    /// Print rebuild progress.
    Status {
        #[arg(long)]
        json: bool,
    },
    /// Print the current losos.* settings from overrides.nix.
    Settings {
        #[arg(long)]
        json: bool,
    },
    /// Print what lososd found when it last looked for an edge proxy.
    Edge {
        #[arg(long)]
        json: bool,
    },
    /// Apply Nix config read from stdin (rewrites overrides.nix, then rebuilds).
    Apply,
    /// Soft factory reset: restore defaults and rebuild.
    ///
    /// The destructive reset — wiping the disks — is the installer ISO, not
    /// this subcommand.
    FactoryReset,
    /// Grow /persist into the volume group's unallocated extents.
    ///
    /// Online: nothing is unmounted and no rebuild is triggered. The space
    /// comes from the margin modules/disko.nix leaves at install time
    /// (losos.storage.fillPercent); when that is exhausted, add a disk with
    /// pvcreate and vgextend and run this again.
    Grow,
    /// Replace the owner's password, read from stdin: the one LosOS Login
    /// checks and their LosOS Git account's.
    ///
    /// Replaces it; there is no way to read the existing one out.
    ///
    /// Stdin and not a flag: /proc/<pid>/cmdline is world-readable, so
    /// `--password hunter2` would publish it to every process on the box.
    ///
    ///   printf %s 'correct horse battery staple' | losos-ctl set-password
    SetPassword {
        /// Account to reset. Defaults to the owner's.
        #[arg(long, default_value = losos_ctl::setup::DEFAULT_ADMIN_USER)]
        user: String,
    },
    /// Print the appliance recovery code, minting one on first use.
    ///
    /// Stable for the life of the installation: the same code comes back on
    /// every later call, and there is no subcommand that replaces it. That is
    /// the point — a code that could be rotated is a code the owner's written
    /// copy stops matching.
    ///
    /// It survives `factory-reset` (which rewrites state.json and
    /// overrides.nix, not /var/secrets) and is destroyed only by a reinstall,
    /// which is the one event it exists for.
    Recovery {
        #[arg(long, hide = true)]
        json: bool,
    },
    /// Print every losos.* option this box declares, with its editor kind,
    /// default, current value and what overrides.nix sets.
    ///
    /// The document the admin UI's Advanced pane is drawn from
    /// (/etc/losos/options.json, generated by nix/options-doc.nix).
    Options {
        #[arg(long, hide = true)]
        json: bool,
    },
    /// Print the configuration repository: its place on LosOS Git, the
    /// branch head, the last commits and how the last sync went.
    ///
    /// /etc/nixos is a git repository; every apply, change and factory-reset
    /// commits there, and lososd keeps it in step with the owner's
    /// repository on LosOS Git every half minute.
    Config {
        /// Sync with LosOS Git now instead of waiting for the next run: push
        /// what the box has, or take a commit pushed from a clone and rebuild.
        #[arg(long, conflicts_with = "update")]
        sync: bool,
        /// Move the configuration to the published branch's newest tree,
        /// keeping this box's own files. The nightly update runs this first;
        /// the rebuild that follows is what installs it.
        #[arg(long)]
        update: bool,
        #[arg(long, hide = true)]
        json: bool,
    },
    /// The losos auto-installer. Destructive: it repartitions every target disk.
    Install(InstallArgs),
    /// Check, as lososd does for an official edge, that an edge's https://
    /// name validates under DNSSEC and its HTTPS record carries an Encrypted
    /// Client Hello key. Runs locally with lososd's resolver settings
    /// ($LOSOS_EDGE_DNS_*); exits 1 when the name does not pass.
    EdgeDomain {
        /// The edge's URL, as its passport names it.
        url: String,
    },
}

/// Flags for the installer. Runs locally; never touches the bus.
#[derive(Args)]
struct InstallArgs {
    /// Seal the disk key to the TPM2 chip. Default wherever a chip is visible;
    /// with this flag a missing chip is an error instead of a keyfile install.
    #[arg(long, conflicts_with = "no_tpm")]
    tpm: bool,
    /// Keep the disk key in the initrd on the boot partition instead of the
    /// TPM2 chip, even where one exists.
    #[arg(long)]
    no_tpm: bool,
    /// Open the disk only with the TPM2 AND this Tang server on the box's
    /// network (Clevis). URL#THUMBPRINT, the thumbprint from tang-show-keys
    /// on the server. Repeat for more servers; any one of them will do.
    #[arg(long = "tang", value_name = "URL#THUMBPRINT", value_parser = parse_tang, conflicts_with = "no_tpm")]
    tang: Vec<Tang>,
    /// Open the disk only with the TPM2 AND this box's edge, which makes a
    /// Tang key for this box alone and stops answering once its owner
    /// reports it stolen. URL: the edge's registrar; without one, the
    /// medium's (losos.proxy.registrarUrl). With --tang as well, the disk
    /// needs the TPM2, a home server and the edge.
    #[arg(long = "tang-edge", value_name = "URL", num_args = 0..=1, default_missing_value = "", conflicts_with = "no_tpm")]
    tang_edge: Option<String>,
    /// Install for legacy BIOS (GRUB). Default: whatever firmware booted this
    /// medium.
    #[arg(long, conflicts_with = "uefi")]
    bios: bool,
    /// Install for UEFI (systemd-boot); requires this medium to boot in UEFI mode.
    #[arg(long)]
    uefi: bool,
    /// Override drive auto-detection with a comma-separated list.
    #[arg(long, value_name = "A,/dev/b,...", value_parser = parse_drives)]
    drives: Option<DriveList>,
    /// Stop after disko (format and mount); skip nixos-install.
    #[arg(long)]
    no_install: bool,
    /// Run a prebuilt diskoScript instead of `disko --flake`.
    #[arg(long, value_name = "PATH")]
    disko_script: Option<PathBuf>,
    /// Write install-target.nix to FILE and exit, touching no disks.
    #[arg(long, value_name = "FILE")]
    emit_target: Option<PathBuf>,
    /// Seed an armoured GPG public key (gpg --armor --export <id>) for the
    /// losos terminal client. Repeat for more than one. Only the installer
    /// seeds keys; the running box cannot add one.
    #[arg(long = "gpg-key", value_name = "FILE")]
    gpg_keys: Vec<PathBuf>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum FirmwareMode {
    Bios,
    Uefi,
    Autodetect,
}

impl FirmwareMode {
    fn parse(choice: &str) -> Option<Self> {
        match choice.trim() {
            "1" => Some(Self::Bios),
            "2" => Some(Self::Uefi),
            "" | "3" => Some(Self::Autodetect),
            _ => None,
        }
    }

    fn bios_override(self) -> Option<bool> {
        match self {
            Self::Bios => Some(true),
            Self::Uefi => Some(false),
            Self::Autodetect => None,
        }
    }
}

/// The parsed `--drives` list.
///
/// A newtype rather than `Vec<String>` because clap reads `Option<Vec<T>>` as
/// "the flag takes many values of T": with a parser that returns the whole Vec
/// it panicked with a type mismatch on first access, so `--drives` crashed
/// before doing anything.
#[derive(Clone, Debug)]
struct DriveList(Vec<String>);

/// Split `--drives a,b,c`, rejecting a list that is empty once trimmed.
fn parse_drives(s: &str) -> Result<DriveList, String> {
    let ds: Vec<String> = s
        .split(',')
        .map(|d| d.trim().to_string())
        .filter(|d| !d.is_empty())
        .collect();
    if ds.is_empty() {
        Err("no drives given".to_string())
    } else {
        Ok(DriveList(ds))
    }
}

/// Reject an invalid mode while parsing, so no bad value ever reaches the bus.
fn parse_mode(s: &str) -> Result<Mode, String> {
    Mode::parse(s).ok_or_else(|| "mode must be 'local' or 'mesh'".to_string())
}

/// How long the ISO's firmware menu waits before taking the default.
///
/// The installer medium is set-and-forget: insert it, boot, walk away. A menu
/// that waits forever would park an unattended reinstall at the prompt, and
/// the CI gate `nix/tests/iso-boot.py`, which never types anything, would time out
/// waiting for the installer's DNS lookup. So no answer means autodetect.
const FIRMWARE_MENU_TIMEOUT: Duration = Duration::from_secs(30);

/// One answer to the firmware prompt, or why there is none.
#[derive(Debug)]
enum MenuInput {
    Line(String),
    Timeout,
    Eof,
}

fn select_firmware(explicit: Option<bool>, interactive: bool) -> std::io::Result<Option<bool>> {
    if let Some(bios) = explicit {
        return Ok(Some(bios));
    }
    if !interactive {
        return Ok(None);
    }
    prompt_firmware(
        read_stdin_line,
        FIRMWARE_MENU_TIMEOUT,
        &mut std::io::stdout(),
    )
}

/// Read one line from stdin, giving up after `timeout`.
///
/// poll(2) rather than a reader thread: a thread left blocked in read_line
/// after a timeout would keep reading the terminal for the rest of the
/// install; disko and systemd-cryptenroll inherit it, and nothing may read
/// from it under them. (Neither prompts any more — both modes format from
/// the generated keyfile — but a stray reader would still eat the first
/// line typed at a later `nmtui`.)
/// The terminal is in canonical mode, so a readable stdin holds one whole
/// line and read_line does not buffer past it.
fn read_stdin_line(timeout: Duration) -> std::io::Result<MenuInput> {
    use rustix::event::{poll, PollFd, PollFlags, Timespec};
    let stdin = std::io::stdin();
    let deadline = Instant::now() + timeout;
    let ready = loop {
        let left = deadline.saturating_duration_since(Instant::now());
        let wait = Timespec::try_from(left).unwrap_or(Timespec {
            tv_sec: i64::MAX,
            tv_nsec: 0,
        });
        let mut fds = [PollFd::new(&stdin, PollFlags::IN)];
        match poll(&mut fds, Some(&wait)) {
            // A signal is not an answer: wait out the rest of the deadline.
            Err(rustix::io::Errno::INTR) => continue,
            other => break other?,
        }
    };
    match ready {
        0 => Ok(MenuInput::Timeout),
        _ => {
            let mut line = String::new();
            if stdin.read_line(&mut line)? == 0 {
                Ok(MenuInput::Eof)
            } else {
                Ok(MenuInput::Line(line))
            }
        }
    }
}

/// The menu itself, over an injectable line source, so the timeout and the
/// retry loop are unit-testable. A timeout or EOF picks autodetect; the
/// deadline is overall, so retyping garbage cannot extend it.
fn prompt_firmware(
    mut read_line: impl FnMut(Duration) -> std::io::Result<MenuInput>,
    timeout: Duration,
    out: &mut impl Write,
) -> std::io::Result<Option<bool>> {
    let deadline = Instant::now() + timeout;
    loop {
        writeln!(out, "Choose the firmware mode for the installed system:")?;
        writeln!(out, "  1) BIOS")?;
        writeln!(
            out,
            "  2) UEFI (requires this installer to be booted in UEFI mode)"
        )?;
        writeln!(
            out,
            "  3) Autodetect (use the firmware that booted this installer)"
        )?;
        write!(
            out,
            "Selection [3, chosen automatically after {}s]: ",
            timeout.as_secs()
        )?;
        out.flush()?;

        let left = deadline.saturating_duration_since(Instant::now());
        match read_line(left)? {
            MenuInput::Line(line) => match FirmwareMode::parse(&line) {
                Some(mode) => return Ok(mode.bios_override()),
                None => writeln!(out, "Choose 1, 2, or 3.")?,
            },
            MenuInput::Timeout => {
                writeln!(out)?;
                writeln!(out, "No choice made; autodetecting.")?;
                return Ok(None);
            }
            MenuInput::Eof => return Ok(None),
        }
    }
}

fn main() -> ExitCode {
    let cli = Cli::parse();

    // The domain check is local too: it is delv and nothing of lososd's.
    if let Command::EdgeDomain { url } = &cli.command {
        let Some(name) = losos_ctl::edge::domain_of(url) else {
            eprintln!("losos-ctl: {url} is not an https:// name");
            return ExitCode::FAILURE;
        };
        let check = losos_ctl::io_backend::check_domain(&name);
        println!(
            "{}",
            serde_json::json!({ "name": name, "signed": check.signed, "ech": check.ech })
        );
        return if check.passed() {
            ExitCode::SUCCESS
        } else {
            ExitCode::FAILURE
        };
    }

    // The installer is local and prints its own progress as it goes; it does
    // not produce a JSON document to relay.
    if let Command::Install(args) = &cli.command {
        // Line-buffering matters when stdout is a pipe: block buffering would
        // hold the installer's own progress lines until exit, after the output
        // of the subprocesses they announce.
        let explicit_bios = match (args.bios, args.uefi) {
            (true, _) => Some(true),
            (_, true) => Some(false),
            _ => None,
        };
        let on_installer_iso = std::env::var_os("LOSOS_INSTALLER_ISO").is_some();
        // The medium's boot screen, when it hosts the installer: the menu,
        // the steps and the result go on its panel, and keys come from it.
        let splash = Splash::detect().filter(|_| on_installer_iso && args.emit_target.is_none());
        let interactive = on_installer_iso
            && std::io::stdin().is_terminal()
            && std::io::stdout().is_terminal()
            && args.emit_target.is_none();
        // Whether the firmware verified this medium before starting it, on
        // the screen before anything else: it is the one place the person
        // who booted the stick can read it (modules/secure-boot.nix).
        if on_installer_iso {
            println!("{}", secure_boot_state().banner());
        }
        let bios = match (splash, explicit_bios) {
            (Some(splash), None) => splash_firmware(splash),
            _ => match select_firmware(explicit_bios, interactive) {
                Ok(bios) => bios,
                Err(e) => {
                    eprintln!("losos-install: cannot read firmware selection: {e}");
                    return ExitCode::FAILURE;
                }
            },
        };
        if let Err(e) = validate_firmware_choice(bios, booted_in_bios()) {
            return install_failed(splash, e);
        }
        let explicit_tpm = match (args.tpm, args.no_tpm) {
            (true, _) => Some(true),
            (_, true) => Some(false),
            _ => None,
        };
        let tpm = match resolve_tpm(explicit_tpm, tpm_present()) {
            Ok(tpm) => tpm,
            Err(e) => return install_failed(splash, &e),
        };
        let gpg_keys = match load_gpg_keys(&args.gpg_keys) {
            Ok(keys) => keys,
            Err(e) => return install_failed(splash, &e),
        };
        let mut opts = options_from_env(
            tpm,
            args.tang.clone(),
            bios,
            args.drives.clone().map(|d| d.0),
            args.no_install,
            args.disko_script.clone(),
            args.emit_target.clone(),
            gpg_keys,
        );
        if let Some(edge) = &args.tang_edge {
            if !opts.tpm {
                return install_failed(
                    splash,
                    "--tang-edge needs the TPM2: the disk key is sealed to the chip AND the edge",
                );
            }
            let edge = if edge.is_empty() {
                std::env::var("LOSOS_REGISTRAR_URL").unwrap_or_default()
            } else {
                edge.clone()
            };
            match request_edge_tang(&edge, &staged_claim(&opts.keyfile)) {
                Ok(t) => opts.tang.push(t),
                Err(e) => return install_failed(splash, &format!("{e:#}")),
            }
        }
        // Memory and processor, sampled while the install runs: the medium
        // runs from memory, so a spike is worth hearing about even when the
        // install finishes.
        let watch = on_installer_iso.then(install_report::Watch::start);
        let result = run_install(&opts, splash);
        let spikes = watch.map(install_report::Watch::finish).unwrap_or_default();
        let disks = opts
            .drives
            .as_ref()
            .map_or_else(|| "picked by the installer".to_owned(), |d| d.join(", "));
        return match result {
            Ok(()) => {
                if let Some(splash) = splash {
                    let installed = !opts.no_install && opts.disko_script.is_none();
                    let target = install_report::target();
                    let report = target.as_ref().and_then(|_| {
                        install::spike_report(&spikes, &install_report::system(), true)
                    });
                    let offer = if report.is_some() {
                        install_screen::Offer::Report
                    } else {
                        install_screen::Offer::None
                    };
                    let lines: Vec<String> = spikes.iter().map(install::Spike::line).collect();
                    let rows = install_screen::finished_with(installed, opts.tpm, &lines, &offer);
                    match (target, report) {
                        (Some(target), Some(report)) => {
                            offer_report(splash, &rows, &target, &report)
                        }
                        _ => {
                            splash.show(&rows);
                            splash.key(None, None, |_| {});
                        }
                    }
                    if installed {
                        // The medium can come out now; nothing on it is
                        // needed again. If the restart fails, the login
                        // wrapper takes over with a shell.
                        let _ = std::process::Command::new("systemctl")
                            .arg("reboot")
                            .status();
                    }
                }
                ExitCode::SUCCESS
            }
            Err(e) => install_failed_with(splash, &format!("{e:#}"), &disks, &spikes),
        };
    }

    match run(cli) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("{e}");
            ExitCode::FAILURE
        }
    }
}

/// The firmware menu on the splash's panel: the same three choices and the
/// same timeout as on text, with the seconds left counting down. Keys
/// other than 1, 2 and 3 are not Plymouth's to pass on, so there is nothing
/// to retype; no answer is autodetect.
fn splash_firmware(splash: Splash) -> Option<bool> {
    let banner = secure_boot_state().banner();
    println!(
        "losos-install: firmware menu on the boot screen: 1 BIOS, 2 UEFI, 3 autodetect \
         (autodetect in {} s)",
        FIRMWARE_MENU_TIMEOUT.as_secs()
    );
    let key = splash.key(Some("123"), Some(FIRMWARE_MENU_TIMEOUT), |left| {
        let secs = left.as_secs_f64().ceil() as u64;
        splash.show(&install_screen::firmware_menu(banner, secs));
    });
    let mode = key.as_deref().and_then(FirmwareMode::parse);
    println!(
        "losos-install: firmware mode: {}",
        match mode {
            Some(FirmwareMode::Bios) => "BIOS",
            Some(FirmwareMode::Uefi) => "UEFI",
            _ => "autodetect",
        }
    );
    mode.and_then(FirmwareMode::bios_override)
}

/// Report a stopped install: on stderr always, and under the splash on its
/// panel too, which waits for a key before the login wrapper takes the
/// splash down and opens a shell under the log.
fn install_failed(splash: Option<Splash>, error: &str) -> ExitCode {
    install_failed_with(splash, error, "", &[])
}

/// A failed install: the banner on tty2, and on the panel what to do about
/// it. A failure the handbook explains names the page; any other, on a
/// medium built to send reports, offers one, and so does a spike.
fn install_failed_with(
    splash: Option<Splash>,
    error: &str,
    disks: &str,
    spikes: &[install::Spike],
) -> ExitCode {
    let banner = format!(
        "\nlosos-install: FAILED\nlosos-install: {error}\nlosos-install: the install stopped. See the lines above on tty2 for the full command output.\n"
    );
    eprintln!("{banner}");
    // Always try tty2 so a failure is explicit even when the splash is up.
    if let Ok(mut tty) = std::fs::OpenOptions::new().write(true).open("/dev/tty2") {
        use std::io::Write;
        let _ = write!(tty, "{banner}");
    }
    if let Some(splash) = splash {
        let failure = install_report::failure(error, disks);
        let documented = install_report::documented(&failure);
        let target = install_report::target();
        let lines: Vec<String> = spikes.iter().map(install::Spike::line).collect();
        let report = match (&target, &documented) {
            (None, _) => None,
            (Some(_), None) => Some(install::failure_report(
                &failure,
                &install_report::system(),
                &install_report::journal(),
                spikes,
            )),
            // The handbook explains the failure; a spike is still news.
            (Some(_), Some(_)) => install::spike_report(spikes, &install_report::system(), false),
        };
        let offer = match (&documented, &report) {
            (_, Some(_)) => install_screen::Offer::Report,
            (Some(known), None) => install_screen::Offer::Documented {
                title: known.title_in("en").to_owned(),
                url: install_report::handbook_url(known),
            },
            (None, None) => install_screen::Offer::None,
        };
        let rows = install_screen::failed_with(error, &lines, &offer);
        match (target, report) {
            (Some(target), Some(report)) => offer_report(splash, &rows, &target, &report),
            _ => {
                splash.show(&rows);
                splash.key(None, None, |_| {});
            }
        }
    }
    ExitCode::FAILURE
}

/// Shows `rows`, which offer a report, with the report on screen 7, and
/// sends it when the person presses R: the code on the panel, any key to
/// stop, the issue's address at the end. Returns once they move on.
fn offer_report(splash: Splash, rows: &[install_screen::Row], target: &Target, report: &Report) {
    use std::sync::atomic::{AtomicBool, Ordering};
    use std::sync::Arc;
    install_report::show(report);
    splash.show(rows);
    let mut key = splash.key(None, None, |_| {});
    while matches!(key.as_deref(), Some("r" | "R")) {
        let cancel = Arc::new(AtomicBool::new(false));
        splash.show(&install_screen::send_starting());
        let stop = cancel.clone();
        let sending = install_report::send_in_background(
            target.clone(),
            report.clone(),
            cancel.clone(),
            move |progress| {
                if stop.load(Ordering::Relaxed) {
                    return;
                }
                splash.show(&match progress {
                    github::Progress::SignIn { uri, code, .. } => {
                        install_screen::send_code(&uri, &code)
                    }
                    github::Progress::Sent { url, existing } => {
                        install_screen::send_done(&url, existing)
                    }
                });
            },
        );
        // A key while it runs stops it; once it has ended, the key is the
        // answer to the screen it ended on.
        let shown = Arc::new(AtomicBool::new(false));
        let ended = shown.clone();
        let failed_screen = std::thread::spawn(move || {
            let result = sending.join().unwrap_or(Err("The sender stopped.".into()));
            if let Err(why) = &result {
                if why != "Cancelled." {
                    splash.show(&install_screen::send_failed(why));
                }
            }
            ended.store(true, Ordering::Relaxed);
            result
        });
        key = splash.key(None, None, |_| {});
        let done = shown.load(Ordering::Relaxed);
        if !done {
            cancel.store(true, Ordering::Relaxed);
        }
        let result = failed_screen.join().unwrap_or(Err("Cancelled.".into()));
        match result {
            Ok(()) => return,
            Err(_) if !done => {
                // Stopped: back to the offer, nothing sent.
                splash.show(rows);
                key = splash.key(None, None, |_| {});
            }
            // Not sent: R tries again, any other key goes on.
            Err(_) => {}
        }
    }
}

fn validate_firmware_choice(
    target_bios: Option<bool>,
    installer_bios: bool,
) -> Result<(), &'static str> {
    if installer_bios && target_bios == Some(false) {
        Err("cannot install for UEFI when the installer was booted in BIOS mode; reboot the installer in UEFI mode")
    } else {
        Ok(())
    }
}

fn run(cli: Cli) -> Result<(), BackendFailure> {
    let json = match cli.command {
        Command::State { .. } => call_backend("State", &())?,
        Command::Status { .. } => call_backend("Status", &())?,
        Command::Settings { .. } => call_backend("Settings", &())?,
        Command::Edge { .. } => call_backend("Edge", &())?,
        Command::Change { mode } => call_backend("Change", &(mode.as_str(),))?,
        Command::FactoryReset => call_backend("FactoryReset", &())?,
        Command::Grow => call_backend("Grow", &())?,
        Command::Recovery { .. } => call_backend("Recovery", &())?,
        Command::Options { .. } => call_backend("Options", &())?,
        Command::Config { sync: true, .. } => call_backend("ConfigSync", &())?,
        Command::Config { update: true, .. } => call_backend("ConfigUpdate", &())?,
        Command::Config { .. } => call_backend("Config", &())?,
        Command::Apply => {
            let mut input = String::new();
            std::io::stdin()
                .read_to_string(&mut input)
                .map_err(|e| BackendFailure(format!("losos-ctl apply: cannot read stdin — {e}")))?;
            // Validate locally so an obviously bad payload fails immediately
            // without a round trip. lososd validates again on its side — this
            // is a convenience, never the security boundary.
            let code = validate_apply(&input)
                .map_err(|e| BackendFailure(format!("losos-ctl apply: {e}")))?;
            call_backend("Apply", &(code,))?
        }
        Command::SetPassword { user } => {
            let mut input = String::new();
            std::io::stdin().read_to_string(&mut input).map_err(|e| {
                BackendFailure(format!("losos-ctl set-password: cannot read stdin — {e}"))
            })?;
            // Exactly one trailing newline, not `trim`: `echo` and every heredoc
            // add one, and a password is allowed to end in a space. Trimming
            // would silently set a different password from the one that was
            // typed, on the one command where nobody can check afterwards.
            let password = input.strip_suffix('\n').unwrap_or(&input);
            let password = password.strip_suffix('\r').unwrap_or(password);
            // Checked locally so an obviously bad password fails without a round
            // trip; lososd validates again, and that is the boundary.
            losos_ctl::setup::validate_password(password)
                .map_err(|e| BackendFailure(format!("losos-ctl set-password: {e}")))?;
            call_backend("SetPassword", &(user.as_str(), password))?
        }
        // Handled before the bus is ever touched.
        Command::Install(_) => unreachable!("install is dispatched in main"),
        Command::EdgeDomain { .. } => unreachable!("edge-domain is dispatched in main"),
    };
    println!("{json}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{prompt_firmware, validate_firmware_choice, Cli, Command, FirmwareMode, MenuInput};
    use clap::Parser;
    use std::time::Duration;

    #[test]
    fn firmware_choices_resolve_as_expected() {
        assert_eq!(FirmwareMode::parse("1"), Some(FirmwareMode::Bios));
        assert_eq!(FirmwareMode::parse("2"), Some(FirmwareMode::Uefi));
        assert_eq!(FirmwareMode::parse("3"), Some(FirmwareMode::Autodetect));
        assert_eq!(FirmwareMode::parse(""), Some(FirmwareMode::Autodetect));
        assert_eq!(FirmwareMode::parse("4"), None);

        assert_eq!(FirmwareMode::Bios.bios_override(), Some(true));
        assert_eq!(FirmwareMode::Uefi.bios_override(), Some(false));
        assert_eq!(FirmwareMode::Autodetect.bios_override(), None);
    }

    #[test]
    fn uefi_install_requires_uefi_booted_installer() {
        assert!(validate_firmware_choice(Some(false), true).is_err());
        assert!(validate_firmware_choice(Some(false), false).is_ok());
        assert!(validate_firmware_choice(Some(true), true).is_ok());
        assert!(validate_firmware_choice(None, true).is_ok());
    }

    /// A scripted line source: each call pops the next answer.
    fn script(mut answers: Vec<MenuInput>) -> impl FnMut(Duration) -> std::io::Result<MenuInput> {
        answers.reverse();
        move |_| Ok(answers.pop().unwrap_or(MenuInput::Eof))
    }

    #[test]
    fn firmware_menu_retries_then_takes_a_valid_choice() {
        let mut out = Vec::new();
        let read = script(vec![
            MenuInput::Line("x\n".into()),
            MenuInput::Line("1\n".into()),
        ]);
        let got = prompt_firmware(read, Duration::from_secs(5), &mut out).unwrap();
        assert_eq!(got, Some(true));
        assert!(String::from_utf8(out)
            .unwrap()
            .contains("Choose 1, 2, or 3."));
    }

    #[test]
    fn firmware_menu_autodetects_on_timeout_and_on_eof() {
        // Unattended boot: nobody types, so the menu must not block the install.
        let mut out = Vec::new();
        let got = prompt_firmware(script(vec![MenuInput::Timeout]), Duration::ZERO, &mut out);
        assert_eq!(got.unwrap(), None);
        assert!(String::from_utf8(out).unwrap().contains("autodetecting"));

        let got = prompt_firmware(script(vec![]), Duration::from_secs(5), &mut Vec::new());
        assert_eq!(got.unwrap(), None);
    }

    #[test]
    fn firmware_menu_deadline_is_overall() {
        // Each re-prompt gets only what is left, never a fresh 30 s.
        let mut budgets = Vec::new();
        let mut first = true;
        let read = |left: Duration| {
            budgets.push(left);
            if std::mem::take(&mut first) {
                std::thread::sleep(Duration::from_millis(20));
                Ok(MenuInput::Line("nope\n".into()))
            } else {
                Ok(MenuInput::Timeout)
            }
        };
        prompt_firmware(read, Duration::from_millis(200), &mut Vec::new()).unwrap();
        assert!(budgets[1] < budgets[0], "{budgets:?}");
    }

    fn install_drives(argv: &[&str]) -> Option<Vec<String>> {
        let cli = Cli::try_parse_from(argv).unwrap();
        match cli.command {
            Command::Install(args) => args.drives.map(|d| d.0),
            _ => panic!("not the install subcommand"),
        }
    }

    #[test]
    fn drives_flag_parses_a_comma_list() {
        // clap reads `Option<Vec<_>>` as "many values of _", so a parser that
        // returns the whole Vec panicked on first access instead of parsing.
        assert_eq!(
            install_drives(&["losos-ctl", "install", "--drives", "vdb, /dev/vdc,,"]),
            Some(vec!["vdb".to_string(), "/dev/vdc".to_string()])
        );
        assert_eq!(install_drives(&["losos-ctl", "install"]), None);
        assert!(Cli::try_parse_from(["losos-ctl", "install", "--drives", " , "]).is_err());
    }
}
