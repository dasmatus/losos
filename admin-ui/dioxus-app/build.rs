//! Generates `defaults.rs` at build time from `admin-ui/app/src/pages/*.mdx`
//! using the losos-mdx pipeline (same crate as the WASM package), producing an
//! embedded HTML map matching the React `losos:pages` DEFAULTS.
//!
//! No runtime MDX parser is used for defaults.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let pages_dir = manifest.join("../app/src/pages");
    let blocks_path = pages_dir.join("blocks.json");

    println!("cargo:rerun-if-changed={}", blocks_path.display());
    println!("cargo:rerun-if-changed={}", pages_dir.display());

    let registry_json = fs::read_to_string(&blocks_path)
        .unwrap_or_else(|e| panic!("read {}: {e}", blocks_path.display()));
    let registry = losos_mdx::page::Registry::from_json(&registry_json)
        .unwrap_or_else(|e| panic!("parse blocks.json: {e}"));

    let mut ids: Vec<String> = registry.pages.keys().cloned().collect();
    ids.sort();

    let mut html_map: BTreeMap<String, String> = BTreeMap::new();
    let mut wrong: Vec<String> = Vec::new();

    for id in &ids {
        let mdx_path = pages_dir.join(format!("{id}.mdx"));
        println!("cargo:rerun-if-changed={}", mdx_path.display());
        if !mdx_path.exists() {
            wrong.push(format!(
                "{id}.mdx: blocks.json lists the page and there is no file"
            ));
            continue;
        }
        let source = fs::read_to_string(&mdx_path)
            .unwrap_or_else(|e| panic!("read {}: {e}", mdx_path.display()));
        let spec = registry.page(id).expect("page listed");
        match losos_mdx::page::render_page(&source, spec) {
            Ok(rendered) => {
                for p in &rendered.problems {
                    let line = p.place.line;
                    let col = p.place.column;
                    wrong.push(format!("{id}.mdx:{line}:{col}: {}", p.message));
                }
                html_map.insert(id.clone(), rendered.html);
            }
            Err(e) => wrong.push(format!("{id}.mdx: {e}")),
        }
    }

    if !wrong.is_empty() {
        panic!("the default pages do not read:\n{}", wrong.join("\n"));
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let mut out = String::new();
    out.push_str("// @generated by build.rs — do not edit.\n");
    out.push_str("// Default page HTML compiled from admin-ui/app/src/pages/*.mdx via losos-mdx.\n\n");
    out.push_str("/// HTML for a default page id, matching React `losos:pages` DEFAULTS.\n");
    out.push_str("pub fn default_html(id: &str) -> Option<&'static str> {\n");
    out.push_str("    match id {\n");
    for (id, html) in &html_map {
        out.push_str(&format!("        {:?} => Some(r###\"{}\"###),\n", id, html));
    }
    out.push_str("        _ => None,\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");
    out.push_str("pub const PAGE_IDS: &[&str] = &[");
    for (i, id) in ids.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("{:?}", id));
    }
    out.push_str("];\n");

    fs::write(out_dir.join("defaults.rs"), out).expect("write defaults.rs");
}
