const ATTRS = {
  strokeLinecap: 'stroke-linecap',
  strokeLinejoin: 'stroke-linejoin',
  strokeWidth: 'stroke-width',
  fillRule: 'fill-rule',
  clipRule: 'clip-rule',
};

const constName = (name) =>
  name
    .replace(/Icon$/, '')
    .replace(/([a-z])([A-Z0-9])/g, '$1_$2')
    .replace(/([0-9])([A-Z])/g, '$1_$2')
    .toUpperCase();

let out = `//! Generated by admin-ui/app/scripts/basic-icons.mjs from
//! @hugeicons/core-free-icons. Do not edit; add a name there and run it.
//!
//! Each constant is the inside of a 24x24 \`<svg>\`; [\`crate::ui::icon\`]
//! wraps it the way @hugeicons/react does.

`;
for (const name of [...NAMES].sort()) {
  const shapes = icons[name];
  if (shapes === undefined) throw new Error(`no icon called ${name}`);
  const inner = shapes
    .map(([tag, attrs]) => {
      const list = Object.entries(attrs)
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${ATTRS[k] ?? k}="${String(v).replace(/"/g, '&quot;')}"`)
        .join(' ');
      return `<${tag} ${list}></${tag}>`;
    })
    .join('');
  out += `pub const ${constName(name)}: &str = r#"${inner}"#;\n`;
}
await Bun.write(`${import.meta.dir}/../../../backend/plugins/page/src/icons.rs`, out);
