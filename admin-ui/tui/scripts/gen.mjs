// Generates src/generated/ from the web UI's own sources, so the terminal
// client cannot drift from them:
//
//   palette.ts        the colour tokens of admin-ui/app/src/styles/tokens.css,
//                     light and dark, as hex and as the nearest xterm-256 index
//   logo.ts           the salmon (admin-ui/themes/brand/salmon-128.png) cut to
//                     its outline and scaled for half-block cells
//   pane-keywords.ts  the English search words of each settings pane, read out
//                     of admin-ui/app/src/screens/settings/panes.ts
//
// Run by `npm run gen`, which build, typecheck and test run first.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const app = join(root, "..", "app");
const out = join(root, "src", "generated");
mkdirSync(out, { recursive: true });

const banner = "// Generated by scripts/gen.mjs. Do not edit; do not commit.\n";

// ── Palette ──────────────────────────────────────────────────────────────

function block(css, selectorStart) {
  const at = css.indexOf(selectorStart);
  if (at < 0) throw new Error(`tokens.css: no block starting ${selectorStart}`);
  const open = css.indexOf("{", at);
  const close = css.indexOf("}", open);
  return css.slice(open + 1, close);
}

function colours(body) {
  const found = {};
  for (const match of body.matchAll(/--([a-z-]+):\s*(#[0-9a-fA-F]{6})\s*;/g)) {
    const name = match[1].replace(/-([a-z])/g, (_, c) => c.toUpperCase());
    found[name] = match[2].toLowerCase();
  }
  return found;
}

function rgbOf(hex) {
  return [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));
}

// The xterm-256 palette: 16 system colours (skipped, they are themeable),
// the 6x6x6 cube and the 24 greys.
const LEVELS = [0, 95, 135, 175, 215, 255];
const XTERM = [];
for (let i = 16; i < 232; i += 1) {
  const n = i - 16;
  XTERM.push([i, [LEVELS[Math.floor(n / 36)], LEVELS[Math.floor(n / 6) % 6], LEVELS[n % 6]]]);
}
for (let i = 232; i < 256; i += 1) {
  const v = 8 + (i - 232) * 10;
  XTERM.push([i, [v, v, v]]);
}

function nearest256(hex) {
  const [r, g, b] = rgbOf(hex);
  let best = 16;
  let bestDistance = Infinity;
  for (const [index, [cr, cg, cb]] of XTERM) {
    // Weighted for the eye: green counts most, blue least.
    const d = 2 * (r - cr) ** 2 + 4 * (g - cg) ** 2 + 3 * (b - cb) ** 2;
    if (d < bestDistance) {
      bestDistance = d;
      best = index;
    }
  }
  return best;
}

const css = readFileSync(join(app, "src", "styles", "tokens.css"), "utf8");
const light = colours(block(css, ":root,\n[data-theme-light]"));
const dark = colours(block(css, ':root[data-theme="dark"]'));
const NAMES = ["ground", "surface", "sunk", "ink", "muted", "faint", "line", "hair", "accent", "accentWash", "ok", "warn", "crit"];
for (const [mode, set] of [["light", light], ["dark", dark]]) {
  for (const name of NAMES) {
    if (set[name] === undefined) throw new Error(`tokens.css: ${mode} has no --${name}`);
  }
}
function paletteOf(set) {
  return Object.fromEntries(NAMES.map((name) => [name, { hex: set[name], ansi256: nearest256(set[name]) }]));
}
writeFileSync(
  join(out, "palette.ts"),
  `${banner}
export type ColourName = ${NAMES.map((n) => JSON.stringify(n)).join(" | ")};
export interface Colour { hex: string; ansi256: number }
export type Palette = Record<ColourName, Colour>;
export const PALETTES: { light: Palette; dark: Palette } = ${JSON.stringify({ light: paletteOf(light), dark: paletteOf(dark) }, null, 2)};
`,
);

// ── Logo ─────────────────────────────────────────────────────────────────

const png = PNG.sync.read(readFileSync(join(root, "..", "themes", "brand", "salmon-128.png")));
const at = (x, y) => {
  const i = (y * png.width + x) * 4;
  return [png.data[i], png.data[i + 1], png.data[i + 2], png.data[i + 3]];
};
let minX = png.width;
let minY = png.height;
let maxX = -1;
let maxY = -1;
for (let y = 0; y < png.height; y += 1) {
  for (let x = 0; x < png.width; x += 1) {
    if (at(x, y)[3] > 24) {
      minX = Math.min(minX, x);
      minY = Math.min(minY, y);
      maxX = Math.max(maxX, x);
      maxY = Math.max(maxY, y);
    }
  }
}
const boxW = maxX - minX + 1;
const boxH = maxY - minY + 1;

// Area-averaged downscale with premultiplied alpha, so the fish's edge does
// not pick up the black of its transparent surroundings.
function scale(cols) {
  let rows = Math.round((cols * boxH) / boxW);
  if (rows % 2 === 1) rows += 1;
  const pixels = [];
  for (let oy = 0; oy < rows; oy += 1) {
    const row = [];
    for (let ox = 0; ox < cols; ox += 1) {
      const x0 = minX + (ox * boxW) / cols;
      const x1 = minX + ((ox + 1) * boxW) / cols;
      const y0 = minY + (oy * boxH) / rows;
      const y1 = minY + ((oy + 1) * boxH) / rows;
      let r = 0;
      let g = 0;
      let b = 0;
      let a = 0;
      let weight = 0;
      for (let y = Math.floor(y0); y < Math.ceil(y1); y += 1) {
        for (let x = Math.floor(x0); x < Math.ceil(x1); x += 1) {
          const wx = Math.min(x + 1, x1) - Math.max(x, x0);
          const wy = Math.min(y + 1, y1) - Math.max(y, y0);
          const w = Math.max(0, wx) * Math.max(0, wy);
          if (w === 0) continue;
          const [pr, pg, pb, pa] = at(Math.min(x, png.width - 1), Math.min(y, png.height - 1));
          const alpha = pa / 255;
          r += pr * alpha * w;
          g += pg * alpha * w;
          b += pb * alpha * w;
          a += alpha * w;
          weight += w;
        }
      }
      if (a === 0) {
        row.push(null);
      } else {
        row.push([Math.round(r / a), Math.round(g / a), Math.round(b / a), Math.round((255 * a) / weight)]);
      }
    }
    pixels.push(row);
  }
  return pixels;
}

writeFileSync(
  join(out, "logo.ts"),
  `${banner}
/** One pixel: red, green, blue, alpha (0-255), or null where the fish is not. */
export type Pixel = readonly [number, number, number, number] | null;
/** Two pixel rows per terminal row, drawn with half blocks. */
export const LOGO_SMALL: readonly (readonly Pixel[])[] = ${JSON.stringify(scale(16))};
export const LOGO_LARGE: readonly (readonly Pixel[])[] = ${JSON.stringify(scale(34))};
`,
);

// ── Pane keywords ────────────────────────────────────────────────────────

const panesSource = readFileSync(join(app, "src", "screens", "settings", "panes.ts"), "utf8");
const keywords = {};
for (const match of panesSource.matchAll(/pane\(\s*"([a-z]+)",\s*\w+,\s*\[([^\]]*)\]/g)) {
  const words = [...match[2].replaceAll(/\/\/[^\n]*/g, "").matchAll(/"([^"]*)"/g)].map((m) => m[1]);
  keywords[match[1]] = words;
}
for (const id of ["storage", "mesh", "apps", "network", "security", "advanced", "history", "backup", "about"]) {
  if (!Array.isArray(keywords[id]) || keywords[id].length === 0) {
    throw new Error(`panes.ts: found no search words for the ${id} pane`);
  }
}
writeFileSync(
  join(out, "pane-keywords.ts"),
  `${banner}
/** English search words per settings pane, as the web UI's sidebar has them. */
export const PANE_KEYWORDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(keywords, null, 2)};
`,
);

console.log(`gen: palette (${NAMES.length} colours x 2), logo (${boxW}x${boxH} cut), ${Object.keys(keywords).length} panes' keywords`);
